#!/usr/bin/env bash
# Merge upstream skills with the brain's own layer into dist/.
# A skill in skills/<name>/ replaces upstream's skill of the same name.
# Skills marked "drop" in catalog.tsv are left out. Writes CATALOG.md.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
UP="$ROOT/upstream/addyosmani-agent-skills"
DIST="$ROOT/dist"
NS="brain"  # plugin name, used to namespace skill references in commands

fit_of() { awk -F'\t' -v s="$1" '$1==s {print $2}' "$ROOT/catalog.tsv"; }
note_of() { awk -F'\t' -v s="$1" '$1==s {print $3}' "$ROOT/catalog.tsv"; }
desc_of() { sed -n 's/^description: //p' "$1" | head -1 | cut -c1-140; }

rm -rf "$DIST"
mkdir -p "$DIST/skills" "$DIST/references" "$DIST/commands" "$DIST/agents"

# Skills: upstream first, then own skills overwrite by name.
for dir in "$UP"/skills/*/; do
  name="$(basename "$dir")"
  [ "$(fit_of "$name")" = "drop" ] && continue
  cp -R "$dir" "$DIST/skills/$name"
done
for dir in "$ROOT"/skills/*/; do
  [ -f "$dir/SKILL.md" ] || continue
  name="$(basename "$dir")"
  rm -rf "$DIST/skills/$name"
  cp -R "$dir" "$DIST/skills/$name"
done

# References, agents, commands: same override rule, by file name.
for kind in references agents; do
  cp "$UP/$kind"/*.md "$DIST/$kind/"
  find "$ROOT/$kind" -maxdepth 1 -name '*.md' ! -name README.md -exec cp {} "$DIST/$kind/" \;
done
for f in "$UP"/.claude/commands/*.md; do
  sed "s/agent-skills:/$NS:/g" "$f" > "$DIST/commands/$(basename "$f")"
done
find "$ROOT/commands" -maxdepth 1 -name '*.md' ! -name README.md -exec cp {} "$DIST/commands/" \;

# Licence for the vendored material travels with it.
cp "$UP/LICENSE" "$DIST/LICENSE-agent-skills"

# Claude Code plugin: dist/ is the plugin root, so skills/, commands/ and agents/ are found by convention.
mkdir -p "$DIST/.claude-plugin"
cp "$ROOT/adapters/claude/plugin.json" "$DIST/.claude-plugin/plugin.json"
cat > "$DIST/README.md" <<'README'
# brain (built output)

This folder is generated by `scripts/build.sh` and is the Claude Code plugin root. It holds the skills, slash commands and subagent personas from addyosmani/agent-skills merged with the brain's own layer, where our own files replace upstream files of the same name. Do not edit anything here; change the source folders in the repository root and rebuild.

Install in Claude Code:

    /plugin install brain --marketplace bravelittle/brain
README

# Catalog.
{
  echo "# Catalog"
  echo
  echo "Generated by \`scripts/build.sh\` from \`catalog.tsv\` and the skill folders. Do not edit by hand."
  echo
  echo "| Skill | Source | Fit | Note | Description |"
  echo "| --- | --- | --- | --- | --- |"
  for dir in "$DIST"/skills/*/; do
    name="$(basename "$dir")"
    if [ -f "$ROOT/skills/$name/SKILL.md" ]; then
      src="own"; [ -d "$UP/skills/$name" ] && src="own (overrides upstream)"
    else
      src="upstream"
    fi
    fit="$(fit_of "$name")"; fit="${fit:-unrated}"
    echo "| \`$name\` | $src | $fit | $(note_of "$name") | $(desc_of "$dir/SKILL.md")... |"
  done
  dropped="$(awk -F'\t' '$2=="drop" {printf "`%s` ", $1}' "$ROOT/catalog.tsv")"
  [ -n "$dropped" ] && { echo; echo "Excluded from the build: $dropped"; }
} > "$ROOT/CATALOG.md"

echo "Built $(ls "$DIST/skills" | wc -l | tr -d ' ') skills into dist/"
